def git(root: Path, *args: str) -> str | None:
    try:
        r = subprocess.run(["git", "-C", str(root), *args], capture_output=True, encoding="utf-8", errors="replace", timeout=30)
    except (OSError, subprocess.SubprocessError):
        return None
    return r.stdout.strip() if r.returncode == 0 else None


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def install(target: Path, name: str, force: bool) -> int:
    fw = target / ".ai-engineering"
    if SRC_FW.resolve() == fw.resolve():
        print("ERROR target is the source installation", file=sys.stderr)
        return 2
    if fw.exists() and not force:
        print(f"REFUSED {fw} already exists (use --force to overwrite the framework files; "
              "MEMORY/, CONFIG/ project files and registries are kept)", file=sys.stderr)
        return 1
    today = dt.date.today().isoformat()
    now = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    head = git(target, "rev-parse", "HEAD") or "pending_owner"
    q = '"' + name.replace('"', "'") + '"'
    fmt = dict(name=name.replace("\n", " "), name_q=q, today=today, now=now, head=head)

    for d in COPY_DIRS:
        dest = fw / d
        if dest.exists():
            shutil.rmtree(dest)
        shutil.copytree(SRC_FW / d, dest, ignore=SKIP)
    for rel in ("CONFIG/model_profiles.yml",):
        (fw / rel).parent.mkdir(parents=True, exist_ok=True)
        if not (fw / rel).exists():
            shutil.copy2(SRC_FW / rel, fw / rel)

    fy = (SRC_FW / "CONFIG/framework.yml").read_text(encoding="utf-8")
    cut = fy.index("implementation_status:")
    fy = fy[:cut] + ("implementation_status:\n  # Template installation: every phase below is what this installation contains, not what is proven.\n"
                     "  phase_E_agent_adapters: delivered_pending_owner_review\n  phase_E_live_cli_conformance: not_run\n")
    created = {
        "CONFIG/framework.yml": fy,
        "CONFIG/project_profile.yml": PROFILE.format(**fmt),
        "CONFIG/command_profiles.yml": COMMANDS.format(**fmt),
        "CONFIG/project_contract_map.yml": CONTRACT.format(**fmt),
        "MEMORY/PROJECT_STATE.yml": STATE.format(**fmt),
        "MEMORY/CURRENT_TASK.md": "# Current Task\n\n**Task:** none\n\nNo active task. The owner names the next work package.\n",
        "MEMORY/KNOWN_ISSUES.md": "# Known issues\n\nNone recorded. Record each with an id, a classification and the next step.\n",
        "MEMORY/COMPLETED_WORK.md": "# Completed work\n\n| Date | Work | Commit | Evidence |\n|---|---|---|---|\n",
        "MEMORY/RECENT_FAILURES.md": "# Recent failures\n\nNone recorded.\n",
        "DOCUMENTATION/FILE_REGISTRY.yml": "# File registry. Validated by SCRIPTS/documentation/check_registry.py.\nfiles: []\n",
        "DOCUMENTATION/FEATURE_REGISTRY.yml": "# Feature registry. Validated by SCRIPTS/documentation/check_registry.py.\nfeatures: []\n",
        "README.md": README.format(**fmt),
    }
    kept = []
    for rel, text in created.items():
        p = fw / rel
        if p.exists():
            kept.append(rel)           # --force never overwrites project state, configuration or registries
            continue
        write(p, text)
    for keep in ("EVIDENCE", "MEMORY/handoffs", "DOCUMENTATION/features"):
        (fw / keep).mkdir(parents=True, exist_ok=True)
        if not any((fw / keep).iterdir()):
            write(fw / keep / ".gitkeep", "")

    # Root entry points. Migration: never overwrite an existing file.
    agents = (SRC_ROOT / "AGENTS.md").read_text(encoding="utf-8")
    gov = re.compile(r"^- Project governance suite:.*$", re.M)
    assert gov.search(agents), "source AGENTS.md changed shape"
    agents = gov.sub("- The project's own governance documents are those named in `.ai-engineering/CONFIG/project_contract_map.yml`.", agents)
    agents = agents.replace("# AGENTS.md - entry point for coding agents (JobHunter)", f"# AGENTS.md - entry point for coding agents ({fmt['name']})")
    proposals = []
    for fname, text in (("AGENTS.md", agents), ("GEMINI.md", (SRC_ROOT / "GEMINI.md").read_text(encoding="utf-8").replace("(JobHunter)", f"({fmt['name']})"))):
        dest = target / fname
        if dest.exists():
            write(target / (fname + ".aef-proposed"), text)
            proposals.append(fname)
        else:
            write(dest, text)

    # Populate the file registry (facts only; every entry stays generated-unreviewed).
    r = subprocess.run([sys.executable, "-I", str(fw / "SCRIPTS/documentation/check_registry.py"), "scan", "--write"],
                       capture_output=True, encoding="utf-8", errors="replace", cwd=target)
    print(f"INSTALLED framework into {fw}")
    for k in kept:
        print(f"KEPT existing {k}")
    for fname in proposals:
        print(f"MIGRATION {fname} already exists and was NOT changed; merge {fname}.aef-proposed into it by hand")
    if r.returncode != 0:
        print("WARN registry scan failed:\n" + r.stdout + r.stderr, file=sys.stderr)
    print("NEXT: set the pending_owner values in .ai-engineering/CONFIG/, then follow WORKFLOW/installation_and_migration.md")
    return 0


def main(argv=None) -> int:
    for s in (sys.stdout, sys.stderr):
        if hasattr(s, "reconfigure"):
            s.reconfigure(errors="replace")
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--target", required=True, type=Path)
    ap.add_argument("--name", required=True)
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args(argv)
    if not a.target.is_dir():
        print(f"ERROR target {a.target} is not a directory", file=sys.stderr)
        return 2
    try:
        return install(a.target.resolve(), a.name, a.force)
    except (OSError, ValueError, AssertionError) as e:
        print(f"ERROR {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
